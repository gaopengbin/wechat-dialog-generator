import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'
const { chromium } = await import(pathToFileURL('C:/Users/Administrator/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs').href)
const output = 'C:/Users/Administrator/Documents/test/outputs/input-borders'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Users/Administrator/AppData/Local/ms-playwright/chromium-1234/chrome-win64/chrome.exe' })
const report = { routes: [], errors: [] }
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  await context.addInitScript(() => localStorage.setItem('wechat-dialog-generator:announcement-read', '2026-09-10-account-v1'))
  await context.route('**/*', route => new URL(route.request().url()).origin === 'http://127.0.0.1:4178' ? route.continue() : route.abort())
  const page = await context.newPage()
  page.on('pageerror', e => report.errors.push(e.message))
  for (const query of ['tool=group', 'tool=redpacket', 'tool=profile', 'tool=payment', 'tool=moments', 'tool=batch', 'tool=chat', 'page=exports']) {
    await page.goto(`http://127.0.0.1:4178/?${query}`)
    await page.locator('.studio-header').waitFor()
    await page.evaluate(() => document.fonts.ready)
    const borders = await page.locator('.ui-input:visible, .ui-textarea:visible, .ui-select-trigger:visible').evaluateAll(nodes => nodes.map(node => ({ name: node.getAttribute('aria-label') || node.id || node.tagName, border: getComputedStyle(node).borderBottomColor })))
    assert.ok(borders.length, query)
    assert.ok(borders.every(item => item.border === 'rgb(214, 223, 217)'), `${query}: ${JSON.stringify(borders)}`)
    report.routes.push({ query, inputs: borders.length })
  }
  const select = page.getByRole('combobox', { name: '筛选工具' })
  await select.hover()
  await page.waitForTimeout(180)
  assert.equal(await select.evaluate(node => getComputedStyle(node).borderColor), 'rgb(185, 202, 190)')
  await select.click()
  await page.getByRole('option', { name: '全部工具', exact: true }).waitFor()
  await page.waitForTimeout(180)
  assert.equal(await select.evaluate(node => getComputedStyle(node).borderColor), 'rgb(7, 131, 68)')
  await page.keyboard.press('Escape')
  await page.goto('http://127.0.0.1:4178/?tool=batch')
  await page.getByRole('button', { name: '模板 Prompt', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '批量聊天模板 Prompt', exact: true })
  await dialog.getByLabel('聊天组数', { exact: true }).fill('51')
  await page.waitForTimeout(180)
  assert.equal(await dialog.getByLabel('聊天组数', { exact: true }).evaluate(node => getComputedStyle(node).borderColor), 'rgb(166, 46, 39)')
  await page.keyboard.press('Escape')
  await page.goto('http://127.0.0.1:4178/?tool=group')
  const name = page.locator('#scene-group-editor input.ui-input').first()
  await name.focus()
  assert.equal(await name.evaluate(node => getComputedStyle(node).outlineColor), 'rgb(7, 131, 68)')
  await name.blur()
  await page.mouse.move(0, 0)
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: `${output}/group-desktop.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: `${output}/group-mobile.png`, fullPage: true })
  assert.deepEqual(report.errors, [])
  await writeFile(`${output}/report.json`, JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
} finally { await browser.close() }
