import { batchLimit } from './batch'

export const BATCH_CHAT_EXAMPLE = `# 项目沟通
【09:30】
我：这版页面今天可以确认吗？
小林：可以，标题再精简一下。
我：好的，下午发你预览。
---
# 周末约饭
小雨：周六有空吗？一起吃饭吧。
我：有空，六点怎么样？
小雨：好，老地方见！
---
# 学习小组
【20:00】
我：今天大家学到什么？
小林：我把表单校验写完了。
小雨：[语音]5：我在练习组件拆分。
我：明天一起交流。`

export const DEFAULT_BATCH_PROMPT = {
  topic: '同事沟通、周末约饭、学习交流',
  count: 3,
  roles: '我、小林、小雨',
}

export function buildBatchPrompt({ topic, count, roles }: typeof DEFAULT_BATCH_PROMPT) {
  const groups = Number.isFinite(count) ? Math.min(batchLimit, Math.max(1, Math.trunc(count))) : DEFAULT_BATCH_PROMPT.count
  return `请为“微信创作工具箱”的批量聊天图功能编写虚构的聊天素材，用于内容创作或产品演示，不冒充真实聊天记录。

本次要求：
- 主题 / 场景：${topic.trim() || DEFAULT_BATCH_PROMPT.topic}
- 聊天组数：${groups} 组，必须恰好输出 ${groups} 组。
- 参与角色：${roles.trim() || DEFAULT_BATCH_PROMPT.roles}。第一位角色作为主要视角，每组让该角色最先发言。
- 每组 8–12 条自然、简短的消息。各组应有独立情节，避免只替换姓名、重复相同对话。

严格遵守以下可直接导入的格式：
1. 只输出一个 text 文本代码块，把全部聊天放在同一个代码块内；代码块外不写解释、前言、序号或表格。不要把每组拆成多个代码块。
2. 每组第一行是“# 聊天标题”（# 后有一个空格），标题不超过 40 字；标题也会用作聊天窗口的联系人 / 群名称。
3. 组与组之间仅用独立一行的三个半角连字符 --- 分隔，一共 ${Math.max(0, groups - 1)} 行分隔线；第一组前和最后一组后都不要加分隔线，不在消息正文中另起一行写 ---。
4. 每条文字消息必须实际换行，格式为“姓名：消息内容”。不能用空格连接多条消息，不能把整组写成一段。使用中文冒号，姓名保持一致，不使用冒号作为姓名的一部分，不添加加粗符号、编号、## 或行尾反斜杠。
5. 可在独立一行插入时间，例如【09:30】。时间行不能代替消息；每组必须有真实的文字对话内容。
6. 需要语音时使用“姓名：[语音]5：转写内容”，其中 5 为语音秒数。默认以文字消息为主，不生成图片占位符、图片链接、红包或转账凭证。
7. 每组不得超过 150 条消息或 10000 字。输出前自检：必须恰好有 ${groups} 行“# 聊天标题”、${Math.max(0, groups - 1)} 行 ---；不要额外扩写其他组。保持各组内容适合阅读和截图。

下面仅演示格式，示例的组数、角色和主题不代表本次要求。请按上面的要求创作新内容，不要复述示例：

\`\`\`text
${BATCH_CHAT_EXAMPLE}
\`\`\``
}
